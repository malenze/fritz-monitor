#!/usr/bin/env python3
"""
EXPERIMENTAL: build FritzMonitor.app, a small AppleScript wrapper that starts the monitor.

Background: a process started directly by launchd has no responsible app, so macOS
silently denies Local Network access (connect() to 192.168.x.x fails with
EHOSTUNREACH). Started through this app, the monitor is a child of the app, so the
permission prompt and the Local Network entry belong to FritzMonitor.app.

Usage (standard library only, run from the checkout):
    python3 build_monitor_app.py            # build FritzMonitor.app in the project root
    python3 build_monitor_app.py --agent    # also rewrite the LaunchAgent plist to start the app
"""

from __future__ import annotations

import argparse
import plistlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import config

APP_NAME = 'FritzMonitor'
APP_BUNDLE_ID = 'com.fritzbox.monitor.app'
APP_PATH = config.PROJECT_ROOT / f'{APP_NAME}.app'
PLIST_PATH = Path.home() / 'Library' / 'LaunchAgents' / f'{config.LAUNCHAGENT_LABEL}.plist'

# Paths are baked in as properties. The pid lives in a global, because properties are
# written back into the applet when it quits, which would break the code signature.
APPLESCRIPT = '''\
-- Generated by build_monitor_app.py
property rootDir : "{root}"
property venvBin : "{venv_bin}"
property pythonBin : "{python}"
property monitorScript : "{script}"
property outLog : "{out_log}"
property errLog : "{err_log}"
property agentLabel : "{label}"

global monitorPid, watchJob

on run
	-- Started by launchd (job is loaded)? Then follow the job: when it is booted out, quit too.
	try
		do shell script "/bin/launchctl print gui/$(id -u)/" & agentLabel
		set watchJob to true
	on error
		set watchJob to false
	end try
	set cmd to "cd " & quoted form of rootDir & " && ALERT_METHOD=desktop PATH=" & quoted form of (venvBin & ":/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin") & " nohup " & quoted form of pythonBin & " " & quoted form of monitorScript & " >> " & quoted form of outLog & " 2>> " & quoted form of errLog & " < /dev/null & echo $!"
	set monitorPid to do shell script cmd
end run

-- Stay-open applet: quit as soon as the monitor is gone (launchd sees `open -W` return),
-- or when the launchd job has been booted out.
on idle
	try
		do shell script "kill -0 " & monitorPid
	on error
		quit
		return 10
	end try
	if watchJob then
		try
			do shell script "/bin/launchctl print gui/$(id -u)/" & agentLabel
		on error
			quit
		end try
	end if
	return 10
end idle

on quit
	try
		do shell script "kill " & monitorPid
	end try
	continue quit
end quit
'''


def applescript_literal(value: str | Path) -> str:
    """Escape a value for use inside an AppleScript double quoted string."""
    return str(value).replace('\\', '\\\\').replace('"', '\\"')


def build_app() -> None:
    """Compile the applet, adjust Info.plist and sign it ad hoc."""
    venv_dir = config.PROJECT_ROOT / 'venv'
    if not (venv_dir / 'bin' / 'python').exists():
        sys.exit(f"venv not found at {venv_dir}. Run macos_setup.py or create it first.")

    log_dir = config.get_log_dir()
    source = APPLESCRIPT.format(
        root=applescript_literal(config.PROJECT_ROOT),
        venv_bin=applescript_literal(venv_dir / 'bin'),
        python=applescript_literal(venv_dir / 'bin' / 'python'),
        script=applescript_literal(config.PROJECT_ROOT / 'fritz_monitor_macos.py'),
        out_log=applescript_literal(log_dir / 'fritz_monitor.out.log'),
        err_log=applescript_literal(log_dir / 'fritz_monitor.error.log'),
        label=applescript_literal(config.LAUNCHAGENT_LABEL),
    )

    if APP_PATH.exists():
        shutil.rmtree(APP_PATH)
    with tempfile.TemporaryDirectory() as tmp:
        script_file = Path(tmp) / f'{APP_NAME}.applescript'
        script_file.write_text(source)
        # -s: stay open, so the idle handler keeps running
        subprocess.run(['osacompile', '-s', '-o', str(APP_PATH), str(script_file)], check=True)

    info_path = APP_PATH / 'Contents' / 'Info.plist'
    with open(info_path, 'rb') as f:
        info = plistlib.load(f)
    info.update({
        'CFBundleIdentifier': APP_BUNDLE_ID,
        'CFBundleName': APP_NAME,
        'LSUIElement': True,  # no Dock icon, no menu bar
        'NSLocalNetworkUsageDescription':
            'FRITZ!Box Monitor reads the router log over the local network.',
    })
    with open(info_path, 'wb') as f:
        plistlib.dump(info, f)

    # Editing Info.plist invalidates the signature, so sign again (ad hoc)
    subprocess.run(['codesign', '--force', '--deep', '--sign', '-', str(APP_PATH)], check=True)
    subprocess.run(['codesign', '--verify', '--deep', '--strict', str(APP_PATH)], check=True)
    print(f"Built {APP_PATH} ({APP_BUNDLE_ID})")


def write_agent_plist() -> None:
    """Rewrite the LaunchAgent plist so launchd starts the app instead of Python directly.

    `open -W` waits until the app quits, so launchd still tracks one job. The program is
    /usr/bin/open itself (no sh, which macOS flags as an unsigned background item), and
    AssociatedBundleIdentifiers ties the item to the app in System Settings. On bootout the
    applet notices that its job is gone within 10 seconds, stops the monitor and quits.
    """
    log_dir = config.get_log_dir()
    agent = {
        'Label': config.LAUNCHAGENT_LABEL,
        'ProgramArguments': ['/usr/bin/open', '-g', '-W', '-a', str(APP_PATH)],
        'AssociatedBundleIdentifiers': [APP_BUNDLE_ID],
        'WorkingDirectory': str(config.PROJECT_ROOT),
        'RunAtLoad': True,
        # The app quits when the monitor dies, which is a clean exit of `open`.
        # SuccessfulExit=false would never restart it, so restart on any exit.
        'KeepAlive': True,
        'ThrottleInterval': 60,
        'StandardOutPath': str(log_dir / 'fritz_monitor.launchd.out.log'),
        'StandardErrorPath': str(log_dir / 'fritz_monitor.launchd.error.log'),
    }
    if PLIST_PATH.exists():
        backup = PLIST_PATH.with_suffix('.plist.direct-python.bak')
        if not backup.exists():
            shutil.copy2(PLIST_PATH, backup)
            print(f"Backup of the previous plist: {backup}")
    PLIST_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(PLIST_PATH, 'wb') as f:
        plistlib.dump(agent, f)
    subprocess.run(['plutil', '-lint', str(PLIST_PATH)], check=True)
    print(f"Wrote {PLIST_PATH}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    parser.add_argument('--agent', action='store_true',
                        help='also rewrite the LaunchAgent plist to start the app')
    args = parser.parse_args()
    build_app()
    if args.agent:
        write_agent_plist()


if __name__ == '__main__':
    main()
